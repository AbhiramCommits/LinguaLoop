-- Experiment framework
-- experiment -> variant -> assignment (deterministic, persisted on first exposure)

CREATE TYPE experiment_status AS ENUM ('DRAFT', 'RUNNING', 'STOPPED');

CREATE TABLE experiment (
    key         VARCHAR(64) PRIMARY KEY,
    description VARCHAR(500) NOT NULL,
    status      experiment_status NOT NULL DEFAULT 'DRAFT',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE variant (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_key VARCHAR(64) NOT NULL REFERENCES experiment (key) ON DELETE CASCADE,
    key            VARCHAR(64) NOT NULL,
    weight         DOUBLE PRECISION NOT NULL CHECK (weight > 0),
    config         JSONB,
    control        BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_variant_experiment_key UNIQUE (experiment_key, key)
);

CREATE TABLE assignment (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learner_id     BIGINT      NOT NULL REFERENCES learner (id) ON DELETE CASCADE,
    experiment_key VARCHAR(64) NOT NULL REFERENCES experiment (key) ON DELETE CASCADE,
    variant_key    VARCHAR(64) NOT NULL,
    assigned_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_assignment_learner_experiment UNIQUE (learner_id, experiment_key)
);

CREATE INDEX idx_assignment_experiment ON assignment (experiment_key, variant_key);

